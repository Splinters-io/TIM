// Level of a finding.
const (
	Info = "info"
	Warn = "warn"
	Bad  = "BAD"
)

type Finding struct {
	Level string
	Msg   string
}

// notableCA is a CA whose history matters to old devices: distrusted by
// browsers (old devices often still trust it) or a long-lived root whose
// expiry stranded devices.
type notableCA struct {
	match []string // lower-case substrings of subject/issuer CN, O or OU
	msg   string
}

